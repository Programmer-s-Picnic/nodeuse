/* JSONP fallback for NodeUse's public, read-only lesson exercises ONLY.
 * A script tag can load JS across origins without a CORS response header.
 * NEVER use JSONP to retrieve secrets, personal data, or authenticated APIs.
 * Only the known GoDaddy lesson host may execute as a JSONP script.
 */
(function () {
  "use strict";
  const TRUSTED_HOST = "11vhaiejwu.c39.airoapp.ai";
  function call(raw, timeoutMs = 9000) {
    const url = new URL(raw);
    if (url.protocol !== "https:" || url.hostname !== TRUSTED_HOST)
      return Promise.reject(new Error("CORS-free fallback only supports the trusted published NodeUse host."));
    if (!url.pathname.startsWith("/api/"))
      return Promise.reject(new Error("Only public teaching routes support this fallback."));
    if (url.searchParams.has("callback"))
      return Promise.reject(new Error("Callback must be generated by the lesson, not supplied in the URL."));
    const random = new Uint32Array(4);
    if (!window.crypto || !window.crypto.getRandomValues)
      return Promise.reject(new Error("Secure random numbers are not available."));
    window.crypto.getRandomValues(random);
    const callback = "__nodeuse_jsonp_" + Array.from(random, n => n.toString(16).padStart(8, "0")).join("");
    url.searchParams.set("callback", callback);
    return new Promise((resolve, reject) => {
      const script = document.createElement("script");
      let settled = false;
      let timer;
      const cleanup = () => {
        clearTimeout(timer);
        script.remove();
        try { delete window[callback]; } catch { window[callback] = undefined; }
      };
      const settle = (error, data) => {
        if (settled) return;
        settled = true;
        cleanup();
        if (error) reject(error);
        else if (data && typeof data === "object" && typeof data.error === "string")
          reject(new Error("GoDaddy API: " + data.error));
        else resolve(data);
      };
      window[callback] = data => settle(null, data);
      script.onerror = () => settle(new Error("The public GoDaddy server did not load the JSONP script. Confirm its exact Published URL and latest deployed version."));
      timer = setTimeout(() => settle(new Error("The JSONP fallback timed out. The published server may not have the updated API.")), timeoutMs);
      script.async = true;
      script.referrerPolicy = "no-referrer";
      script.src = url.href;
      document.head.appendChild(script);
    });
  }
  window.NodeUseJSONP = Object.freeze({ call });
})();